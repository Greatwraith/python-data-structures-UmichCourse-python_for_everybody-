# Fungsi range mengembalikan daftar angka yang berkisar dari nol hingga satu kurang dari parameter.

friends = ['Joseph', 'Glenn', 'Robert', 'Damian', 'Victor']


# mencetak panjang/isi list
print(len(friends)) # output : 5 karena ada 5 item.

# mencetak/iterasi indexnya  
print(list(range(len(friends)))) # output : 0,1,2,3,4  -  karena index nya dari 1 sampai 4 
# items di list pada umumnya disusun berurutan(in order)
# kita bisa mengubah urutan items menjadi Alphabetical order(disusun sesuai alphabet nya)
# di list menggunakan method sort

name_to_alphabeticalOrder = ['Ardhan', 'Damian', 'Elliot','Bardy', 'Collin']
name_to_alphabeticalOrder.sort() # METHOD NYA
print(name_to_alphabeticalOrder)





# akan di sort menjadi Alphabetical order A.K.A disusun sesuai alphabet

# BEFORE
# Ardhan | Damian | Elliot | Bardy | Collin
#   A    |   D    |    E   |   B   |    C 
# 
#  ADEBC > tidak sesuai urutan alphabet

# AFTER
# AFTER | Menjadi beurutan sesuai urutan Alphabet(Alphabetical order)
# Ardhan | Bardy | Collin | Damian | Elliot
#   A    |   B   |   C    |    D   |    E   
#    
#  ABCD > Menjadi beurutan sesuai urutan Alphabet(Alphabetical order)
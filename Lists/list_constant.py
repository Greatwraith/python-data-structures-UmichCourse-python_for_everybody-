# sebuah List dapat berupa objek Python apa pun — bahkan list lagi(list di dalam list).
# List juga bisa empty, artinya tidak memiliki elemen apa pun di dalamnya. seperti ini: [].


# List dapat menyimpan berbagai jenis data, termasuk angka, string, dan bahkan list lainnya.
print([1, 24, 76])


# List dapat menyimpan string, dikelilingi oleh tanda kutip tungga/ganda 'iniContohnya' & "iniContohnya".
print(['red', 'yellow', 'blue'])


# List juga dapat menyimpan list lain di dalamnya, yang disebut nested list atau list bersarang.
print([1, [5, 6], 7])


# List dapat menyimpan berbagai jenis data sekaligus, termasuk angka, string, dan bahkan list lainnya.
print([1, 'red', 3.14, 'yellow', [5, 6], 7])


# List juga bisa empty, artinya tidak memiliki elemen apa pun di dalamnya. seperti ini: [].

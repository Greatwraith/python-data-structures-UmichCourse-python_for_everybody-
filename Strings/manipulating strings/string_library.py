greet = 'hello, world!'


# Metode upper() digunakan untuk mengubah semua huruf dalam string menjadi huruf kapital.
toUpperCase = greet.upper()
print(toUpperCase)

# Metode lower() digunakan untuk mengubah semua huruf dalam string menjadi huruf kecil.
toLowerCase = greet.lower()
print(toLowerCase)


# Metode capitalize() digunakan untuk mengubah huruf pertama dari string menjadi huruf kapital,
# sedangkan huruf lainnya tetap kecil.
Capitalized = greet.capitalize()
print(Capitalized)



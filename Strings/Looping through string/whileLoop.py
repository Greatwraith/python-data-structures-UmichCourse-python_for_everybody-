fruit = 'watermelon'
index = 0

while index < len(fruit):
    letter = fruit[index]
    print(index, letter)
    index += 1
    
    
# While loop menelusuri setiap karakter dalam string satu per satu menggunakan index.
# Loop berhenti saat index mencapai panjang string, dan index bertambah 1 tiap iterasi.